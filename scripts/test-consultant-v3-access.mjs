#!/usr/bin/env node
import assert from "node:assert/strict";

const BASE_URL = process.env.BASE_URL || "http://127.0.0.1:3000";
const GOLDEN_RUN_ID = "00000000-0000-4000-8000-000000000401";
const GOLDEN_ALIAS = "run-v3-golden-01";
const INVALIDATED_RUN_ID = "d0f8978a-8260-446e-83f6-0f7a3957875e";

console.log("=== MatchBASE Consultant V3 Access Control Test Suite ===");

async function getAuthCookie(fixtureRole) {
  const r1 = await fetch(
    `${BASE_URL}/auth/simulator/start?fixture=${fixtureRole}`,
    {
      redirect: "manual",
    },
  );
  assert.equal(r1.status, 302, "Simulator start must return 302 redirect");
  const callbackUrl = r1.headers.get("location");
  const startCookie = r1.headers.get("set-cookie");

  const r2 = await fetch(`${BASE_URL}${callbackUrl}`, {
    redirect: "manual",
    headers: { cookie: startCookie || "" },
  });
  assert.equal(r2.status, 303, "Simulator callback must return 303 redirect");
  const rawCookies = r2.headers.getSetCookie
    ? r2.headers.getSetCookie()
    : [r2.headers.get("set-cookie")];
  const sessionCookie = rawCookies
    .map((c) => c?.split(";")[0])
    .filter(Boolean)
    .join("; ");
  assert.ok(
    sessionCookie.includes("matchbase_session="),
    `Must establish valid session cookie for ${fixtureRole}`,
  );
  return sessionCookie;
}

async function runTests() {
  console.log("\n1. Testing PDF Endpoint Authorization...");

  // 1a. Unauthenticated -> 401
  const unauthPdfRes = await fetch(
    `${BASE_URL}/api/v1/consultant/reports/${GOLDEN_RUN_ID}/pdf`,
  );
  assert.equal(
    unauthPdfRes.status,
    401,
    `Unauthenticated PDF request must return 401, got ${unauthPdfRes.status}`,
  );
  console.log("✔ Unauthenticated PDF request correctly rejected with HTTP 401");

  // 1b. Standard User -> 403
  const standardCookie = await getAuthCookie("standard");
  const standardPdfRes = await fetch(
    `${BASE_URL}/api/v1/consultant/reports/${GOLDEN_RUN_ID}/pdf`,
    {
      headers: { Cookie: standardCookie },
    },
  );
  assert.equal(
    standardPdfRes.status,
    403,
    `Standard user PDF request must return 403, got ${standardPdfRes.status}`,
  );
  console.log("✔ Standard user PDF request correctly rejected with HTTP 403");

  // 1c. Consultant User -> 200 application/pdf
  const consultantCookie = await getAuthCookie("consultant");
  const consultantPdfRes = await fetch(
    `${BASE_URL}/api/v1/consultant/reports/${GOLDEN_RUN_ID}/pdf`,
    {
      headers: { Cookie: consultantCookie },
    },
  );
  assert.equal(
    consultantPdfRes.status,
    200,
    `Consultant PDF request must return 200, got ${consultantPdfRes.status}`,
  );
  const contentType = consultantPdfRes.headers.get("content-type");
  assert.ok(
    contentType?.includes("application/pdf"),
    `Content-Type must be application/pdf, got ${contentType}`,
  );
  const pdfBytes = await consultantPdfRes.arrayBuffer();
  assert.ok(
    pdfBytes.byteLength > 10000,
    `PDF must contain generated bytes, got ${pdfBytes.byteLength}`,
  );
  console.log(
    `✔ Consultant PDF request returned HTTP 200 with ${pdfBytes.byteLength} bytes`,
  );

  // 1d. Alias routing -> 200 application/pdf
  const aliasPdfRes = await fetch(
    `${BASE_URL}/api/v1/consultant/reports/${GOLDEN_ALIAS}/pdf`,
    {
      headers: { Cookie: consultantCookie },
    },
  );
  assert.equal(
    aliasPdfRes.status,
    200,
    `Consultant PDF alias request must return 200, got ${aliasPdfRes.status}`,
  );
  console.log(
    "✔ Consultant PDF alias request correctly resolved with HTTP 200",
  );

  // 1e. Invalidated Run -> 410 Gone
  const invalidPdfRes = await fetch(
    `${BASE_URL}/api/v1/consultant/reports/${INVALIDATED_RUN_ID}/pdf`,
    {
      headers: { Cookie: consultantCookie },
    },
  );
  assert.equal(
    invalidPdfRes.status,
    410,
    `Invalidated run PDF request must return 410 Gone, got ${invalidPdfRes.status}`,
  );
  console.log(
    "✔ Invalidated run PDF request correctly rejected with HTTP 410 Gone",
  );

  console.log("\n2. Testing Consultant Workflow API Authorization...");

  // 2a. Unauthenticated GET workflow -> 401
  const unauthWorkflowRes = await fetch(
    `${BASE_URL}/api/v1/consultant/workflow`,
  );
  assert.equal(
    unauthWorkflowRes.status,
    401,
    `Unauthenticated workflow request must return 401, got ${unauthWorkflowRes.status}`,
  );
  console.log(
    "✔ Unauthenticated workflow request correctly rejected with HTTP 401",
  );

  // 2b. Standard User GET workflow -> 403
  const standardWorkflowRes = await fetch(
    `${BASE_URL}/api/v1/consultant/workflow`,
    {
      headers: { Cookie: standardCookie },
    },
  );
  assert.equal(
    standardWorkflowRes.status,
    403,
    `Standard user workflow request must return 403, got ${standardWorkflowRes.status}`,
  );
  console.log(
    "✔ Standard user workflow request correctly rejected with HTTP 403",
  );

  // 2c. Consultant User GET workflow -> 200
  const consultantWorkflowRes = await fetch(
    `${BASE_URL}/api/v1/consultant/workflow?run_id=${GOLDEN_RUN_ID}`,
    {
      headers: { Cookie: consultantCookie },
    },
  );
  assert.equal(
    consultantWorkflowRes.status,
    200,
    `Consultant workflow request must return 200, got ${consultantWorkflowRes.status}`,
  );
  console.log("✔ Consultant workflow request authorized with HTTP 200");

  // 2d. Invalidated Run on Workflow route -> 410
  const invalidWorkflowRes = await fetch(
    `${BASE_URL}/api/v1/consultant/workflow?run_id=${INVALIDATED_RUN_ID}`,
    {
      headers: { Cookie: consultantCookie },
    },
  );
  assert.equal(
    invalidWorkflowRes.status,
    410,
    `Invalidated run on workflow route must return 410 Gone, got ${invalidWorkflowRes.status}`,
  );
  console.log(
    "✔ Invalidated run on workflow route correctly rejected with HTTP 410 Gone",
  );

  console.log("\n=======================================================");
  console.log("✔ ALL CONSULTANT V3 ACCESS CONTROL TESTS PASSED!");
  console.log("=======================================================");
}

runTests().catch((err) => {
  console.error("❌ Access control test failed:", err);
  process.exit(1);
});
